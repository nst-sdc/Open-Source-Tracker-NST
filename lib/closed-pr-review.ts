/**
 * lib/closed-pr-review.ts
 *
 * Why do students' pull requests get closed without merging, and what did
 * the maintainers say? Pure classification of one closed PR from what
 * GitHub returns for it (comments, reviews, labels, who closed it), and a
 * summary over many. Storage and fetching live in lib/kv-closed-prs.ts and
 * lib/closed-pr-fetch.ts; the admin "Closed PRs" tab shows the result and
 * lets an admin promote a maintainer quote, with names removed, to the
 * public Don'ts on /get-started.
 */

export const CLOSED_PR_WINDOW_MONTHS = 12;

export type ClosedBy = 'author' | 'bot' | 'maintainer' | 'unknown';

export const REASONS = [
  'withdrawn by student, no feedback',
  'withdrawn by student after feedback',
  'AI-generated / low-effort / spam',
  'stale, closed by a bot',
  'process: no issue, not assigned, CLA',
  'duplicate / superseded',
  'out of scope / not wanted',
  'changes requested, not completed',
  'closed by maintainer, no comment',
  'other (maintainer commented)',
] as const;
export type Reason = (typeof REASONS)[number];

/** What a maintainer's words were about; several can apply to one comment. */
export const FLAGS = ['ai', 'warning', 'process', 'ping', 'duplicate', 'low-quality', 'incomplete', 'scope', 'stale'] as const;
export type Flag = (typeof FLAGS)[number];

export interface Quote {
  by: 'maintainer' | 'bot';
  /** GitHub login of the commenter; never shown publicly. */
  login: string;
  body: string;
  createdAt?: string;
  flags: Flag[];
}

export interface ClosedPrFeedback {
  key: string; // repo#number
  repo: string;
  number: number;
  url: string;
  title: string;
  login: string;
  campus?: string;
  year?: string;
  createdAt: string;
  closedAt?: string;
  closedBy: ClosedBy;
  labels: string[];
  linesChanged: number;
  reason: Reason;
  flags: Flag[];
  /** Human maintainers' comments and reviews, newest last, at most a few. */
  quotes: Quote[];
  scannedAt: string;
}

/** The slice of GitHub's GraphQL answer the classifier reads. */
export interface PrDetail {
  state?: string;
  closedAt?: string | null;
  createdAt?: string;
  additions?: number;
  deletions?: number;
  author?: { login: string } | null;
  labels?: { nodes: Array<{ name: string }> };
  timelineItems?: { nodes: Array<{ actor?: { login: string } | null; createdAt?: string }> };
  comments?: { nodes: Array<{ author?: { login: string } | null; body: string; createdAt?: string }> };
  reviews?: { nodes: Array<{ author?: { login: string } | null; state: string; body: string; createdAt?: string }> };
  reviewThreads?: { nodes: Array<{ comments: { nodes: Array<{ author?: { login: string } | null; body: string; createdAt?: string }> } }> };
}

const BOT = /\[bot\]$|^(github-actions|dependabot|stale|codecov|coderabbitai|copilot|copilot-pull-request-reviewer|cubic-dev-ai|mergify|renovate|cla-assistant|welcome|boring-cyborg|gitguardian|pre-commit-ci|changeset-bot|allcontributors|dosubot|greptile|graphite-app|sonarcloud|netlify|vercel|deepsource|gemini-code-assist|sympy-bot|k8s-ci-robot|kubestellar-prow|packit-as-a-service|codesandbox|cypress|lgtm|pr-labeler|linear|height|nx-cloud)$/i;
export const isBotLogin = (login: string | null | undefined): boolean => Boolean(login) && BOT.test(login as string);

const PATTERNS: Record<Flag, RegExp> = {
  ai: /ai[- ]generated|\bai slop\b|\bslop\b|\bllm\b|chatgpt|generated by (ai|an ai|chat)|ai (usage|policy|use policy|contributions? policy)|looks? (like )?(ai|automated|generated)|written by (ai|an llm)|using (ai|an? llm)|rely(ing)? on ai|low[- ]effort/i,
  warning: /\bban(ned)?\b|will be blocked|you.ve been warned|warned multiple|if this continues|reported (the|your) account|stop (opening|submitting|spamming|creating)|do not (open|submit|create) (any )?(more|further)|please (stop|refrain)/i,
  process: /open an issue|create an issue|file an issue|without (an )?(issue|discussion)|discuss(ion)? first|not assigned|get assigned|assigned to (someone|another)|claim(ed)? (the|this) issue|before (opening|submitting|working)|read (the|our) contribut|\bcla\b|\bdco\b|sign(ed)?[- ]off/i,
  ping: /stop (pinging|tagging)|refrain (from )?(pinging|tagging)|no need to (tag|ping|mention)|don.t (ping|tag|@)/i,
  duplicate: /\bduplicate|\bdupe\b|already (been )?(fixed|addressed|done|merged|implemented|open|exists)|already (have|has) (a|an|one) (pr|pull request) open|someone else|another pr|superseded|\bspam(ming|my)?\b/i,
  'low-quality': /low[- ]quality|trivial|cosmetic|no (real )?value|nothing (significant|of value)|just rewords?|unnecessary|not meaningful|bike.?shed|meaningless/i,
  incomplete: /incomplete|does not (work|compile|build)|doesn.t (work|compile)|tests? (fail|are failing)|ci (is )?fail|broken|not tested|didn.t (test|run)|conflict|rebase|changes requested/i,
  scope: /out of scope|not (in|within) scope|not planned|won.t fix|wontfix|not (going to|something we)|not needed|no need|not necessary|by design|intended|decline|not accept|we don.t accept/i,
  stale: /\bstale\b|inactivity|no activity|closing (this )?(pr )?(as|due to) (it|lack|no)/i,
};

export function flagsIn(text: string): Flag[] {
  return FLAGS.filter((f) => PATTERNS[f].test(text));
}

const clip = (s: string, n = 600) => s.replace(/\s+/g, ' ').trim().slice(0, n);

/** Classifies one closed PR. `meta` is what the profile cache knows; `d` is GitHub's answer. Pure. */
export function classifyClosedPr(
  meta: { repo: string; number: number; url: string; title: string; login: string; campus?: string; year?: string; createdAt: string; closedAt?: string | null },
  d: PrDetail,
  nowIso = new Date().toISOString(),
): ClosedPrFeedback {
  const author = (d.author?.login ?? meta.login).toLowerCase();
  const labels = (d.labels?.nodes ?? []).map((l) => l.name.toLowerCase());
  const closeEv = d.timelineItems?.nodes?.[0];
  const closer = (closeEv?.actor?.login ?? '').toLowerCase();
  const closedBy: ClosedBy = !closer ? 'unknown' : closer === author ? 'author' : isBotLogin(closer) ? 'bot' : 'maintainer';

  const quotes: Quote[] = [];
  const add = (login: string | undefined | null, body: string | undefined, createdAt?: string) => {
    if (!login || !body || login.toLowerCase() === author) return;
    const by = isBotLogin(login) ? 'bot' : 'maintainer';
    quotes.push({ by, login, body: clip(body), createdAt, flags: flagsIn(body) });
  };
  for (const c of d.comments?.nodes ?? []) add(c.author?.login, c.body, c.createdAt);
  for (const r of d.reviews?.nodes ?? []) add(r.author?.login, r.body, r.createdAt);
  for (const t of d.reviewThreads?.nodes ?? []) for (const c of t.comments.nodes) add(c.author?.login, c.body, c.createdAt);
  const human = quotes.filter((q) => q.by === 'maintainer');
  const changesRequested = (d.reviews?.nodes ?? []).some((r) => r.state === 'CHANGES_REQUESTED' && (r.author?.login ?? '').toLowerCase() !== author);
  const humanFlags = new Set<Flag>(human.flatMap((q) => q.flags));
  const labelFlags = new Set<Flag>(flagsIn(labels.join(' ')));
  const has = (f: Flag) => humanFlags.has(f) || labelFlags.has(f);

  let reason: Reason;
  if (closedBy === 'bot' || labels.includes('stale') || (has('stale') && closedBy !== 'author')) reason = 'stale, closed by a bot';
  else if (closedBy === 'author' && human.length === 0) reason = 'withdrawn by student, no feedback';
  else if (closedBy === 'author') reason = 'withdrawn by student after feedback';
  else if (has('ai') || labels.includes('spam') || labels.includes('invalid')) reason = 'AI-generated / low-effort / spam';
  else if (has('duplicate') || labels.includes('duplicate')) reason = 'duplicate / superseded';
  else if (has('process')) reason = 'process: no issue, not assigned, CLA';
  else if (has('scope') || labels.includes('wontfix') || labels.includes("won't fix") || labels.includes('not planned')) reason = 'out of scope / not wanted';
  else if (changesRequested || has('incomplete') || has('low-quality')) reason = 'changes requested, not completed';
  else if (human.length === 0) reason = 'closed by maintainer, no comment';
  else reason = 'other (maintainer commented)';

  // Keep the quotes that carry a signal, then the rest, newest last, few.
  const kept = [...human.filter((q) => q.flags.length > 0), ...human.filter((q) => q.flags.length === 0)].slice(0, 6);
  return {
    key: `${meta.repo}#${meta.number}`,
    repo: meta.repo,
    number: meta.number,
    url: meta.url,
    title: clip(meta.title, 160),
    login: meta.login,
    campus: meta.campus,
    year: meta.year,
    createdAt: meta.createdAt,
    closedAt: d.closedAt ?? meta.closedAt ?? undefined,
    closedBy,
    labels,
    linesChanged: (d.additions ?? 0) + (d.deletions ?? 0),
    reason,
    flags: [...new Set([...humanFlags, ...labelFlags])],
    quotes: kept,
    scannedAt: nowIso,
  };
}

/** A maintainer's words with the people taken out: mentions, profile links, emails, and the student's own name. */
export function anonymizeQuote(body: string, logins: string[] = []): string {
  let s = body.replace(/\r/g, '').replace(/<!--[\s\S]*?-->/g, '');
  s = s.replace(/https?:\/\/github\.com\/[A-Za-z0-9-]+(?=[\s)>\]"']|$)/g, 'https://github.com/…');
  s = s.replace(/[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}/gi, '…@…'); // before mentions, which would eat the domain
  s = s.replace(/@[A-Za-z0-9-]+(\[bot\])?/g, '@…');
  for (const l of logins) if (l) s = s.replace(new RegExp(l.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi'), '…');
  return s.replace(/[ \t]{2,}/g, ' ').replace(/[ \t]+\n/g, '\n').replace(/\n{3,}/g, '\n\n').trim();
}

export interface StudentRow { login: string; campus?: string; year?: string; closed: number; ai: number; warnings: number; keys: string[] }
export interface ClosedPrSummary {
  total: number;
  reasons: Array<{ reason: Reason; count: number }>;
  closedBy: Record<ClosedBy, number>;
  byOwner: Array<{ owner: string; count: number; top: Reason }>;
  byMonth: Array<{ month: string; closed: number; ai: number; warnings: number }>;
  /** Per campus: closures, and how many were called AI-generated or carried a warning. */
  byCampus: Array<{ campus: string; count: number; ai: number; warnings: number; top: Reason }>;
  byYear: Array<{ year: string; count: number; ai: number; warnings: number }>;
  students: StudentRow[];
  /** PRs with at least one flagged human comment, most serious first. */
  flagged: Array<{ key: string; url: string; repo: string; login: string; reason: Reason; flags: Flag[]; quote: Quote }>;
  lastScanAt?: string;
}

const WEIGHT: Record<Flag, number> = { warning: 5, ai: 4, ping: 3, process: 2, 'low-quality': 2, duplicate: 1, incomplete: 1, scope: 1, stale: 0 };

export function summarizeClosedPrs(list: ClosedPrFeedback[]): ClosedPrSummary {
  const reasons = new Map<Reason, number>();
  const closedBy: Record<ClosedBy, number> = { author: 0, bot: 0, maintainer: 0, unknown: 0 };
  const owners = new Map<string, Map<Reason, number>>();
  const months = new Map<string, { closed: number; ai: number; warnings: number }>();
  const campuses = new Map<string, { count: number; ai: number; warnings: number; reasons: Map<Reason, number> }>();
  const years = new Map<string, { count: number; ai: number; warnings: number }>();
  const students = new Map<string, StudentRow>();
  const flagged: ClosedPrSummary['flagged'] = [];
  let lastScanAt: string | undefined;
  for (const r of list) {
    reasons.set(r.reason, (reasons.get(r.reason) ?? 0) + 1);
    closedBy[r.closedBy]++;
    const owner = r.repo.split('/')[0];
    const om = owners.get(owner) ?? new Map<Reason, number>();
    om.set(r.reason, (om.get(r.reason) ?? 0) + 1);
    owners.set(owner, om);
    const m = r.createdAt.slice(0, 7);
    const mm = months.get(m) ?? { closed: 0, ai: 0, warnings: 0 };
    mm.closed++;
    if (r.flags.includes('ai')) mm.ai++;
    if (r.flags.includes('warning')) mm.warnings++;
    months.set(m, mm);
    const c = campuses.get(r.campus ?? 'unknown') ?? { count: 0, ai: 0, warnings: 0, reasons: new Map<Reason, number>() };
    c.count++; if (r.flags.includes('ai')) c.ai++; if (r.flags.includes('warning')) c.warnings++;
    c.reasons.set(r.reason, (c.reasons.get(r.reason) ?? 0) + 1);
    campuses.set(r.campus ?? 'unknown', c);
    const y = years.get(r.year ?? 'unknown') ?? { count: 0, ai: 0, warnings: 0 };
    y.count++; if (r.flags.includes('ai')) y.ai++; if (r.flags.includes('warning')) y.warnings++;
    years.set(r.year ?? 'unknown', y);
    const s = students.get(r.login) ?? { login: r.login, campus: r.campus, year: r.year, closed: 0, ai: 0, warnings: 0, keys: [] };
    s.closed++;
    if (r.flags.includes('ai')) s.ai++;
    if (r.flags.includes('warning')) s.warnings++;
    if (r.flags.includes('ai') || r.flags.includes('warning')) s.keys.push(r.key);
    students.set(r.login, s);
    const best = r.quotes.filter((q) => q.by === 'maintainer' && q.flags.length > 0).sort((a, b) => score(b.flags) - score(a.flags))[0];
    if (best) flagged.push({ key: r.key, url: r.url, repo: r.repo, login: r.login, reason: r.reason, flags: best.flags, quote: best });
    if (!lastScanAt || r.scannedAt > lastScanAt) lastScanAt = r.scannedAt;
  }
  flagged.sort((a, b) => score(b.flags) - score(a.flags) || a.key.localeCompare(b.key));
  return {
    total: list.length,
    reasons: REASONS.map((reason) => ({ reason, count: reasons.get(reason) ?? 0 })).filter((x) => x.count > 0).sort((a, b) => b.count - a.count),
    closedBy,
    byOwner: [...owners.entries()].map(([owner, om]) => {
      const count = [...om.values()].reduce((a, b) => a + b, 0);
      const top = [...om.entries()].sort((a, b) => b[1] - a[1])[0][0];
      return { owner, count, top };
    }).sort((a, b) => b.count - a.count).slice(0, 25),
    byMonth: [...months.entries()].sort().map(([month, v]) => ({ month, ...v })),
    byCampus: [...campuses.entries()].map(([campus, c]) => ({ campus, count: c.count, ai: c.ai, warnings: c.warnings, top: [...c.reasons.entries()].sort((a, b) => b[1] - a[1])[0][0] })).sort((a, b) => b.count - a.count),
    byYear: [...years.entries()].map(([year, y]) => ({ year, ...y })).sort((a, b) => b.count - a.count),
    students: [...students.values()].sort((a, b) => b.warnings - a.warnings || b.ai - a.ai || b.closed - a.closed).slice(0, 60),
    flagged: flagged.slice(0, 200),
    lastScanAt,
  };
}
function score(flags: Flag[]) { return flags.reduce((n, f) => n + WEIGHT[f], 0); }

export interface Dont {
  id: string;
  /** Anonymised maintainer words. */
  quote: string;
  /** e.g. "apache/airflow", shown as context. */
  repo: string;
  /** Month the comment was written, e.g. "Mar 2026". */
  when?: string;
  /** Which rule it illustrates. */
  lesson: string;
  addedAt: string;
}
